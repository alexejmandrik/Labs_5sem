-- 14. Создайте АБ, распечатывающий следующие списки аудиторий: 
-- все аудитории (таблица AUDITORIUM) с вместимостью меньше 20, от 21-30, от 31-60, от 61 до 80, от 81 и выше. 

DECLARE
  CURSOR c_aud (p_min NUMBER, p_max NUMBER) IS
    SELECT AUDITORIUM, AUDITORIUM_NAME, AUDITORIUM_CAPACITY
    FROM AUDITORIUM
    WHERE AUDITORIUM_CAPACITY BETWEEN p_min AND p_max
    ORDER BY AUDITORIUM_CAPACITY;

  v_aud   AUDITORIUM.AUDITORIUM%TYPE;
  v_name  AUDITORIUM.AUDITORIUM_NAME%TYPE;
  v_cap   AUDITORIUM.AUDITORIUM_CAPACITY%TYPE;

BEGIN
  DBMS_OUTPUT.PUT_LINE('===== 0–20 =====');

  OPEN c_aud(0, 20);
  LOOP
    FETCH c_aud INTO v_aud, v_name, v_cap;
    EXIT WHEN c_aud%NOTFOUND;
    DBMS_OUTPUT.PUT_LINE(v_aud || ' | ' || v_name || ' | ' || v_cap);
  END LOOP;
  CLOSE c_aud;

  DBMS_OUTPUT.PUT_LINE('===== 21–30 =====');

  OPEN c_aud(21, 30);
  FETCH c_aud INTO v_aud, v_name, v_cap;

  WHILE c_aud%FOUND LOOP
    DBMS_OUTPUT.PUT_LINE(v_aud || ' | ' || v_name || ' | ' || v_cap);
    FETCH c_aud INTO v_aud, v_name, v_cap;
  END LOOP;

  CLOSE c_aud;

  DBMS_OUTPUT.PUT_LINE('===== 31–60 =====');

  FOR rec IN c_aud(31, 60) LOOP
    DBMS_OUTPUT.PUT_LINE(rec.AUDITORIUM || ' | ' ||
                         rec.AUDITORIUM_NAME || ' | ' ||
                         rec.AUDITORIUM_CAPACITY);
  END LOOP;

  DBMS_OUTPUT.PUT_LINE('===== 61–80 =====');

  FOR rec IN c_aud(61, 80) LOOP
    DBMS_OUTPUT.PUT_LINE(rec.AUDITORIUM || ' | ' ||
                         rec.AUDITORIUM_NAME || ' | ' ||
                         rec.AUDITORIUM_CAPACITY);
  END LOOP;

  DBMS_OUTPUT.PUT_LINE('===== 81+ =====');

  FOR rec IN c_aud(81, 9999) LOOP
    DBMS_OUTPUT.PUT_LINE(rec.AUDITORIUM || ' | ' ||
