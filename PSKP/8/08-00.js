const http = require('http');
const fs = require('fs');
const path = require('path');
const url = require('url');
let mp=require('multiparty');

let keepAliveTimeout = 5000; // 5 сек

const parseBody = (req, callback) => {
    let body = '';
    req.on('data', chunk => body += chunk);
    req.on('end', () => callback(body));
};

const http_handler = (req, res) => {
    const parsedUrl = url.parse(req.url, true);
    const pathname = parsedUrl.pathname;
    const query = parsedUrl.query;

    //connection?set=4000
    if (pathname === '/connection') {
        const socket = req.socket;
        console.log(`[${new Date().toISOString()}] TCP соединение открыто: ${socket.remoteAddress}:${socket.remotePort}, ${parseInt(query.set)};`);

        socket.on('close', () => {
            console.log(`[${new Date().toISOString()}] TCP соединение закрыто: ${socket.remoteAddress}:${socket.remotePort}, ${parseInt(query.set)};`);
        });

        if (query.set) {
            keepAliveTimeout = parseInt(query.set);
            server.keepAliveTimeout = keepAliveTimeout;
            res.writeHead(200, {'Content-Type': 'text/plain; charset=utf-8' });
            res.end(`Новое значение KeepAliveTimeout=${keepAliveTimeout}`);
        } else {
            res.writeHead(200, {'Content-Type': 'text/plain; charset=utf-8'});
            res.end(`Текущее значение KeepAliveTimeout=${keepAliveTimeout}`);
        }
    }

    //
   else if (pathname === '/headers') {

        res.setHeader('X-User-Header', 'MAI');
        res.writeHead(200, {
            'Content-Type': 'application/json; charset=utf-8'
        });
        res.end(JSON.stringify({
            requestHeaders: req.headers,
            responseHeaders: res.getHeaders()
        }, null, 2));
    }

    //parameter?x=100&&y=2
    else if (pathname === '/parameter' && query.x && query.y) {
        const x = parseFloat(query.x);
        const y = parseFloat(query.y);
        if (!isNaN(x) && !isNaN(y)) {
            res.writeHead(200, {'Content-Type': 'text/plain; charset=utf-8'});
            res.end(`Сумма:${x+y}, Разность:${x-y}, Произведение:${x*y}, Частное:${x/y}`);
        } else {
            res.writeHead(400, {'Content-Type': 'text/plain; charset=utf-8'});
            res.end('Ошибка: x и y должны быть числами');
        }
    }

    //parameter/10/2
    else if (pathname.startsWith('/parameter/')) {
        const parts = pathname.split('/').filter(Boolean);
        if (parts.length === 3) {
            const x = parseFloat(parts[1]);
            const y = parseFloat(parts[2]);
            if (!isNaN(x) && !isNaN(y)) {
                res.writeHead(200, {'Content-Type': 'text/plain; charset=utf-8'});
                res.end(`Сумма:${x+y}, Разность:${x-y}, Произведение:${x*y}, Частное:${x/y}`);
            } else {
                res.writeHead(200, {'Content-Type': 'text/plain; charset=utf-8'});
                res.end(`URI: ${pathname}`);
            }
        }
    }

    //
    else if (pathname === '/close') {
        res.writeHead(200, {'Content-Type': 'text/plain; charset=utf-8'});
        res.end('Сервер закроется через 10 секунд');
        console.log('Сервер закроется через 10 секунд');
        setTimeout(() =>{ 
            console.log('Сервер закрыт'); 
            process.exit(0);
        }, 10000);   
    }

    //
    else if (pathname === '/socket') {
        const socket = req.socket;
        res.writeHead(200, {'Content-Type': 'text/plain'});
        res.end(`Клиентик:${socket.remoteAddress}:${socket.remotePort}\nСервер:${socket.localAddress}:${socket.localPort}`);
    }

    //
    else if (pathname === '/req-data') {
        res.writeHead(200, {'Content-Type':'text/plain; charset=utf-8'});
        let buffer='';
        req.on('data', (data)=>{res.write(`req.on(data) =  ${data.length}\n`); buffer+=data;})
        req.on('end',()=>res.end());
    }

    //resp-status?code=412&mess=ggg
    else if (pathname === '/resp-status') {
        const code = query.code || 200;
        const mess = query.mess || 'OK';
        res.statusCode=code;
        res.statusMessage=mess;
        res.writeHead(res.statusCode,res.statusMessage, {'Content-Type':'text/plain'});
        res.end(`${res.statusCode}: ${res.statusMessage}`);
    }

    //
    else if (pathname === '/formparameter' && req.method === 'POST') {
        parseBody(req, body => {
            res.writeHead(200, {'Content-Type': 'text/plain; charset=utf-8'});
            res.end(`Параметры:\n${body}`);
        });
    }



// {
//     "__comment": "Запросю Лабораторная работа 8/10",
//     "x": 1,
//     "y": 2,
//     "s": "Message",
//     "m": ["a", "b", "c", "d"],
//     "o":{"surname": "Иванов", "name": "Иван"}
// }
    else if (pathname === '/json' && req.method === 'POST') {
        parseBody(req, body => {
            try {
                const data = JSON.parse(body);
                const response = {
                    "__comment": "Ответ.Лабораторная работа 8/10",
                    "x_plus_y": data.x + data.y,
                    "Concatination_s_o": `${data.s}: ${data.o.surname}, ${data.o.name}`,
                    "Length_m": data.m.length
                };
                res.writeHead(200, {'Content-Type': 'application/json'});
                res.end(JSON.stringify(response, null, 2));
            } catch (e) {
                res.writeHead(400, {'Content-Type': 'text/plain; charset=utf-8'});
                res.end('Ошибка');
            }
        });
    }

    
//<request id="28">
    //<x value="1"/>
    //<x value="2"/>
    //<m value="a"/>
    //<m value="b"/>
    //<m value="c"/>
//</request>

    else if (pathname === '/xml' && req.method === 'POST') {
        parseBody(req, body => {
            const idMatch = body.match(/<request\s+id="(\d+)"\s*>/);
            const requestId = idMatch ? idMatch[1] : '0';
            const xMatches = [...body.matchAll(/<x value="(\d+)"/g)];
            const mMatches = [...body.matchAll(/<m value="([^"]+)"/g)];
            const sumX = xMatches.reduce((acc, m) => acc + parseInt(m[1]), 0);
            const concatM = mMatches.map(m => m[1]).join('');
            const responseXML = `<response id="33" request="${requestId}"><sum element="x" result="${sumX}"/><concat element="m" result="${concatM}"/></response>`;
            res.writeHead(200, {'Content-Type': 'application/xml'});
            res.end(responseXML);
        });
    }

    //
    else if (pathname === '/files' && req.method === 'GET') {
        fs.readdir('./static', (err, files) => {
            if (err) {
                res.writeHead(500, {'Content-Type': 'text/plain; charset=utf-8'});
                res.end('Ошибка. Директорий не найден');
                return;
            }
            const response = {
                count: files.length,
                files: files
            };
            res.writeHead(200, {
                'Content-Type': 'application/json',
                'X-static-files-count': files.length
            });
            res.end(JSON.stringify(response, null, 2));
        });
    }

    //
    else if (pathname.startsWith('/files/')) {
        const filename = decodeURIComponent(pathname.split('/')[2]);
        const filePath = path.join(__dirname, 'static', filename);
        fs.readFile(filePath, (err, data) => {
            if (err) {
                res.writeHead(404, {'Content-Type': 'text/plain; charset=utf-8'})
                res.end('Файл не найден');
                return;
            }
            res.writeHead(200);
            res.end(data);
        });
    }

    //
    else if (pathname === '/upload') {
        if (req.method === 'GET') {
            res.writeHead(200, {'Content-Type': 'text/html; charset=utf-8'});
            res.end(`<form method="POST" enctype="multipart/form-data">
                        <input type="file" name="file"/><br/>
                        <input type="submit" value="Upload"/>
                    </form>`);
        } else if (req.method === 'POST') {
            const form = new mp.Form({ uploadDir: './static' });

            form.on("file", (name, file) => {
                const originalPath = path.join('./static', file.originalFilename);

                fs.rename(file.path, originalPath, (err) => {
                    if (err) console.error("Ошибка сохранения файла:", err);
                    else console.log(`Файл сохранён как: ${file.originalFilename}`);
                });
            });

            form.on("error", (err) => {
                res.writeHead(500, { "Content-Type": "text/plain; charset=utf-8" });
                res.end("Ошибка загрузки");
            });

            form.on("close", () => {
                res.writeHead(200, { "Content-Type": "text/plain; charset=utf-8" });
                res.end("Файл успешно загружен");
            });
            form.parse(req);
        }
    }

    else {
        res.writeHead(404, {'Content-Type': 'text/plain; charset=utf-8'});
        res.end('Маршрут не найден');
    }
};

const server = http.createServer();
server.listen(3000, () => { console.log('Server http://localhost:3000'); }).on('request', http_handler);

server.keepAliveTimeout = keepAliveTimeout;


